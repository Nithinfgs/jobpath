"""Markdown (for job summaries / PR comments), JSON and standalone HTML output."""

from __future__ import annotations

import html
import json
import re
from typing import Any, Dict, List, Set, Tuple

from .analyze import PathNode, RunAnalysis, Summary, fmt_dur, fmt_range, insights
from .model import Job


def _mermaid_name(name: str) -> str:
    return re.sub(r"[:;#,]", " ", name).strip() or "job"


def _rows(a: RunAnalysis, limit: int) -> Tuple[List[Job], Set[int]]:
    critical = {n.job.id for n in a.path}
    jobs = sorted(a.run.jobs, key=lambda j: j.started)
    keep = [j for j in jobs if j.id in critical]
    rest = sorted((j for j in jobs if j.id not in critical), key=lambda j: -j.duration)
    keep += rest[: max(0, limit - len(keep))]
    keep.sort(key=lambda j: j.started)
    return keep, critical


def render_markdown(summary: Summary, title: str, rows: int = 16) -> str:
    a = summary.typical
    n = len(summary.analyses)
    L: List[str] = [f"## jobpath: {title}", ""]
    L.append(
        f"**Median wall time {fmt_dur(summary.median_wall)}**"
        + (f" (p90 {fmt_dur(summary.p90_wall)})" if n > 1 else "")
        + f" · job time {fmt_dur(summary.median_job_seconds)}"
        + f" · parallelism {summary.median_parallelism:.1f}x · {n} run{'s' if n != 1 else ''}"
    )
    L += ["", "### Findings", ""]
    found = insights(summary)
    L += [f"- {f}" for f in found] or ["- Nothing stands out."]

    L += ["", f"### Timeline of run [#{a.run.id}]({a.run.url or '#'}) ({fmt_dur(a.wall)})", ""]
    keep, critical = _rows(a, rows)
    L += ["```mermaid", "gantt", "  dateFormat X", "  axisFormat %M:%S", "  section Critical path"]
    for i, j in enumerate([j for j in keep if j.id in critical]):
        s, e = int(a.offset(j.started)), int(a.offset(j.completed))
        L.append(f"  {_mermaid_name(j.name)} :crit, c{i}, {s}, {max(e, s + 1)}")
    others = [j for j in keep if j.id not in critical]
    if others:
        L.append("  section Other jobs")
        for i, j in enumerate(others):
            s, e = int(a.offset(j.started)), int(a.offset(j.completed))
            L.append(f"  {_mermaid_name(j.name)} :o{i}, {s}, {max(e, s + 1)}")
    L += [
        "```",
        "",
        "### Critical path",
        "",
        "| # | Job | Wait | Run | −30% saves |",
        "|---|---|---:|---:|---:|",
    ]
    for i, node in enumerate(a.path, 1):
        g = a.gains[node.job.id]
        L.append(
            f"| {i} | {node.job.name} | {fmt_dur(node.latency)} | {fmt_dur(node.duration)} | {fmt_range(g.faster_30, g.faster_30_max)} |"
        )
    if n > 1:
        L += [
            "",
            f"### Jobs by impact (over {n} runs)",
            "",
            "| Job | On path | Median | p90 | −30% saves |",
            "|---|---:|---:|---:|---:|",
        ]
        for js in summary.jobs[:8]:
            if js.critical:
                L.append(
                    f"| {js.name} | {js.critical}/{n} | {fmt_dur(js.median_duration)} | "
                    f"{fmt_dur(js.p90_duration)} | {fmt_range(js.median_gain_30, js.median_gain_30_max)} |"
                )
    L += [
        "",
        "<sub>Critical path is inferred from job timestamps; savings are simulated, not measured. "
        "Generated by [jobpath](https://github.com/Nithinfgs/jobpath).</sub>",
        "",
    ]
    return "\n".join(L)


def render_json(summary: Summary, title: str) -> str:
    a = summary.typical

    def node(n: PathNode) -> Dict[str, Any]:
        g = a.gains[n.job.id]
        return {
            "job": n.job.name,
            "wait_seconds": n.latency,
            "queue_seconds": n.queue,
            "run_seconds": n.duration,
            "categories": {k: v for k, v in n.categories.items() if v},
            "saves_if_30_percent_faster": {"min": g.faster_30, "max": g.faster_30_max},
            "saves_if_removed": {"min": g.removed, "max": g.removed_max},
        }

    data = {
        "target": title,
        "runs": len(summary.analyses),
        "median_wall_seconds": summary.median_wall,
        "p90_wall_seconds": summary.p90_wall,
        "median_job_seconds": summary.median_job_seconds,
        "median_parallelism": summary.median_parallelism,
        "setup_share_of_job_time": summary.setup_share,
        "critical_path_categories": summary.path_categories,
        "typical_run": {"id": a.run.id, "wall_seconds": a.wall, "critical_path": [node(n) for n in a.path]},
        "jobs": [
            {
                "job": j.name,
                "runs": j.appearances,
                "on_critical_path": j.critical,
                "median_seconds": j.median_duration,
                "p90_seconds": j.p90_duration,
                "median_queue_seconds": j.median_queue,
                "median_saves_if_30_percent_faster": {"min": j.median_gain_30, "max": j.median_gain_30_max},
                "expected_saving_per_run_seconds": j.expected_gain_30,
            }
            for j in summary.jobs
        ],
        "findings": insights(summary),
    }
    return json.dumps(data, indent=2)


