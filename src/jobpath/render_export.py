def render_html(summary: Summary, title: str) -> str:
    a = summary.typical
    keep, critical = _rows(a, 60)
    label_w, chart_w, row_h = 250, 620, 22
    scale = chart_w / a.wall if a.wall else 0
    bars = []
    for i, j in enumerate(keep):
        y = i * row_h + 4
        q0 = label_w + a.offset(j.created) * scale
        s0 = label_w + a.offset(j.started) * scale
        w = max(1.5, j.duration * scale)
        cls = "var(--crit)" if j.id in critical else "var(--oth)"
        name = html.escape(j.name if len(j.name) < 38 else j.name[:37] + "…")
        bars.append(
            f'<text x="{label_w - 8}" y="{y + 13}" text-anchor="end">{name}</text>'
            f'<rect x="{q0:.1f}" y="{y}" width="{max(0, s0 - q0):.1f}" height="16" fill="var(--q)"/>'
            f'<rect x="{s0:.1f}" y="{y}" width="{w:.1f}" height="16" rx="2" fill="{cls}"><title>{html.escape(j.name)}: {fmt_dur(j.duration)}</title></rect>'
            f'<text x="{s0 + w + 5:.1f}" y="{y + 13}">{fmt_dur(j.duration)}</text>'
        )
    path_rows = "".join(
        f"<tr><td>{i}</td><td>{html.escape(n.job.name)}</td><td class='n'>{fmt_dur(n.latency)}</td>"
        f"<td class='n'>{fmt_dur(n.duration)}</td><td class='n'>{fmt_range(a.gains[n.job.id].faster_30, a.gains[n.job.id].faster_30_max)}</td></tr>"
        for i, n in enumerate(a.path, 1)
    )
    n = len(summary.analyses)
    stats = (
        f"Median wall {fmt_dur(summary.median_wall)} · job time {fmt_dur(summary.median_job_seconds)} · "
        f"parallelism {summary.median_parallelism:.1f}x · {n} run{'s' if n != 1 else ''}"
    )
    return _HTML.format(
        title=html.escape(title),
        stats=stats,
        findings="".join(f"<li>{html.escape(f)}</li>" for f in insights(summary))
        or "<li>Nothing stands out.</li>",
        run_id=a.run.id,
        wall=fmt_dur(a.wall),
        height=len(keep) * row_h + 8,
        bars="".join(bars),
        path=path_rows,
    )
